"""Lean 4 adapter: the production proof backend.

STATUS: NEXT STEP, NOT IMPLEMENTED.

The repair loop in this repo verifies candidates by property-based
testing (see checker.py). That finds counterexamples fast, but it is not
a proof. The production design is:

1. ``emit_lean_theorem(spec, code)`` renders the spec as Lean 4
   definitions and theorem statements (skeleton only, with ``sorry``).
2. A human or a future ``LeanBackend`` implementation feeds that file to
   the ``lean`` toolchain; ``sorry`` must be discharged before the
   artifact is accepted as verified.
3. ``verify_with_lean`` is the interface that step will implement. It
   raises NotImplementedError until the Lean toolchain is integrated,
   rather than pretending to prove anything.

Nothing in this module claims a proof exists. The example file
``examples/sort.lean`` shows the intended output shape.
"""

from __future__ import annotations

from .spec import Spec

# Theorem names emitted per spec. The statements themselves are written
# as comments: generating real Lean propositions from the Python
# postconditions is part of the production work.
_THEOREMS = {
    "sort": [
        ("sort_list_sorted", "(sort_list xs).Sorted (· ≤ ·)"),
        ("sort_list_perm", "(sort_list xs) ~ xs"),
    ],
    "binary_search": [
        ("binary_search_found", "x ∈ xs → xs[binary_search xs x] = x"),
        ("binary_search_absent", "x ∉ xs → binary_search xs x = -1"),
    ],
    "dedup": [
        ("dedup_nodup", "(dedup xs).Nodup"),
        ("dedup_mem", "y ∈ dedup xs ↔ y ∈ xs"),
    ],
}


def emit_lean_theorem(spec: Spec, code_source: str) -> str:
    """Render a Lean 4 skeleton for ``spec``.

    The Python implementation is embedded as a comment for reference.
    Every theorem ends in ``sorry``: this file is a starting point for a
    real proof, not a proof.
    """
    theorems = _THEOREMS.get(spec.name, [("spec_holds", "True")])
    lines = [
        f"-- Auto-generated by proofcarver for spec: {spec.name}",
        f"-- {spec.description}",
        "-- STATUS: skeleton only. Each theorem ends in `sorry` and must",
        "-- be discharged with the Lean 4 toolchain before this counts",
        "-- as a verified artifact.",
        "",
        "-- Reference implementation (Python, for the human prover):",
    ]
    for line in code_source.rstrip().splitlines():
        lines.append(f"--   {line}")
    lines.append("")
    lines.append(f"def {spec.func_name}Impl : List Int → List Int := sorry")
    lines.append("")
    for name, statement in theorems:
        lines.append(f"theorem {name} (xs : List Int) : {statement} := by")
        lines.append("  sorry")
        lines.append("")
    return "\n".join(lines)


def verify_with_lean(spec: Spec, code_source: str) -> bool:
    """Run the Lean 4 toolchain over the emitted skeleton.

    Not implemented: this repo has no Lean toolchain dependency, and
    returning True here would be a false claim of verification.
    """
    raise NotImplementedError(
        "Lean 4 backend not implemented: install the Lean toolchain and "
        "implement proof discharge for emit_lean_theorem() output. "
        "See ARCHITECTURE.md."
    )
